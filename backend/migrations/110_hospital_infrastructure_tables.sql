-- ── Shared updated_at trigger function ──────────────────────────────────────
CREATE OR REPLACE FUNCTION public.royan_touch_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

